"""Retrieval experiments: {dense, bm25, hybrid, hybrid+rerank} x {article, fixed}.

Writes evals/results/retrieval.json (all numbers + per-question rows) and
evals/results/retrieval.md (the tables used in the README).

Usage: uv run python -m evals.runners.run_retrieval [--modes ...] [--strategies ...]
"""

from __future__ import annotations

import argparse
import platform
from datetime import UTC, datetime

from marjaa.config import get_settings
from marjaa.evaluation.dataset import load_testset
from marjaa.evaluation.experiments import MODES, STRATEGIES, evaluate_retrieval, write_json
from marjaa.logging_utils import get_logger, setup_logging
from marjaa.retrieval.retriever import build_retriever

log = get_logger("eval.retrieval")

LABEL = {
    "dense": "Dense (BGE-M3)",
    "bm25": "BM25",
    "hybrid": "Hybrid (RRF)",
    "hybrid_rerank": "Hybrid + rerank",
}
TYPE_LABEL = {
    "ar": "Arabic",
    "en": "English",
    "cross_ar_en": "AR question → EN text",
    "cross_en_ar": "EN question → AR text",
    "multi": "Multi-article",
}


def to_markdown(results: list[dict], meta: dict) -> str:
    lines = [
        f"<!-- generated by evals/runners/run_retrieval.py on {meta['date']} -->",
        f"Questions: {meta['n_questions']} answerable (all splits). "
        f"Embedder `{meta['embedder']}`, reranker `{meta['reranker']}`.",
        "",
        "| Chunking | Retrieval | Recall@1 | Recall@5 | Recall@10 | MRR | nDCG@10 | p50 latency |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        o = r["overall"]
        lines.append(
            f"| {r['strategy']} | {LABEL[r['mode']]} | {o['recall@1']:.3f} | {o['recall@5']:.3f} "
            f"| {o['recall@10']:.3f} | {o['mrr']:.3f} | {o['ndcg@10']:.3f} "
            f"| {r['latency']['p50_ms']:.0f} ms |"
        )
    lines += ["", "Recall@5 by question type:", ""]
    types = list(results[0]["by_type"])
    lines.append(
        "| Chunking | Retrieval | " + " | ".join(TYPE_LABEL.get(t, t) for t in types) + " |"
    )
    lines.append("|---|---|" + "---|" * len(types))
    for r in results:
        cells = " | ".join(f"{r['by_type'][t]['recall@5']:.3f}" for t in types)
        lines.append(f"| {r['strategy']} | {LABEL[r['mode']]} | {cells} |")
    lines.append("")
    lines.append(
        "n per type: "
        + ", ".join(f"{TYPE_LABEL.get(t, t)} = {results[0]['by_type'][t]['n']}" for t in types)
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--modes", nargs="+", default=MODES)
    parser.add_argument("--strategies", nargs="+", default=STRATEGIES)
    parser.add_argument("--out", default="retrieval")
    args = parser.parse_args()
    setup_logging()
    settings = get_settings()
    items = load_testset(settings.testset_path)

    results = []
    for strategy in args.strategies:
        retriever = build_retriever(settings, strategy)
        for mode in args.modes:
            res = evaluate_retrieval(retriever, items, mode)
            res["strategy"] = strategy
            results.append(res)
            log.info("config done", extra={"strategy": strategy, "mode": mode, **res["overall"]})

    meta = {
        "date": datetime.now(UTC).strftime("%Y-%m-%d"),
        "n_questions": results[0]["n"],
        "embedder": settings.embedding_model if settings.embedder != "hashing" else "hashing",
        "reranker": settings.reranker_model if settings.embedder != "hashing" else "overlap",
        "machine": f"{platform.machine()} {platform.system()}",
        "testset": str(settings.testset_path.name),
    }
    out = settings.results_dir
    write_json(out / f"{args.out}.json", {"meta": meta, "results": results})
    (out / f"{args.out}.md").write_text(to_markdown(results, meta), encoding="utf-8")
    print((out / f"{args.out}.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
