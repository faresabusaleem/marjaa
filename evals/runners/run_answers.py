"""Answer quality on the TEST split: LLM-judged correctness and faithfulness,
code-checked citations, "not found" behaviour and latency.

Writes evals/results/answers.json and evals/results/answers.md.

Usage: uv run python -m evals.runners.run_answers [--split test] [--limit N]
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime

from marjaa.config import get_settings
from marjaa.evaluation.dataset import load_testset
from marjaa.evaluation.experiments import evaluate_answers, write_json
from marjaa.generation.answer import RagPipeline
from marjaa.generation.providers import get_provider
from marjaa.logging_utils import setup_logging
from marjaa.retrieval.retriever import build_retriever
from marjaa.service import effective_settings


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def to_markdown(summary: dict, meta: dict) -> str:
    s, lat = summary, summary["latency"]
    rows = [
        ("Correctness (judge, answered questions)", pct(s["correctness"])),
        ("Faithfulness to sources (judge)", pct(s["faithfulness"])),
        ("Correct over all answerable (abstain = wrong)", pct(s["correct_over_all_answerable"])),
        (
            "Citation validity (cites a retrieved article, code-checked)",
            pct(s["citation_validity"]),
        ),
        ("Answers with at least one citation", pct(s["answers_with_citation"])),
        ("Gold article cited", pct(s["gold_article_cited"])),
        ("Sentences carrying a citation", pct(s["citation_coverage"])),
        (
            "Answers containing text from the prompt's format example",
            "n/a" if s.get("format_example_leaks") is None else str(s["format_example_leaks"]),
        ),
        ("Unanswerable → correctly said 'not found'", pct(s["unanswerable_abstention"])),
        ("Answerable → wrongly said 'not found'", pct(s["false_abstention"])),
        (
            "Latency p50 / p95, retrieval",
            f"{lat['retrieval']['p50_ms']:.0f} / {lat['retrieval']['p95_ms']:.0f} ms",
        ),
        (
            "Latency p50 / p95, first token",
            f"{lat['first_token']['p50_ms']:.0f} / {lat['first_token']['p95_ms']:.0f} ms"
            if lat["first_token"]
            else "n/a",
        ),
        (
            "Latency p50 / p95, full answer",
            f"{lat['total']['p50_ms']:.0f} / {lat['total']['p95_ms']:.0f} ms",
        ),
    ]
    lines = [
        f"<!-- generated by evals/runners/run_answers.py on {meta['date']} -->",
        f"Split `{meta['split']}`: {s['n_answerable']} answerable + {s['n_unanswerable']} "
        f"unanswerable questions. Generator `{meta['generator']}`, judge `{meta['judge']}`, "
        f"retrieval `{meta['retrieval']}`, not-found threshold {meta['min_relevance']}.",
        "",
        "| Metric | Value |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in rows],
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--split", default="test", choices=["dev", "test", "all"])
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--out", default="answers")
    parser.add_argument(
        "--fresh", action="store_true", help="Ignore a checkpoint left by an interrupted run"
    )
    args = parser.parse_args()
    setup_logging()
    settings = effective_settings(get_settings())
    items = load_testset(settings.testset_path)
    if args.split != "all":
        items = [i for i in items if i.split == args.split]
    items = items[: args.limit] if args.limit else items

    provider = get_provider(settings)
    judge = get_provider(settings, settings.judge_provider, model=settings.judge_model)
    pipeline = RagPipeline(build_retriever(settings), provider, settings)
    config = {
        "split": args.split,
        "limit": args.limit,
        "generator": f"{provider.name}:{provider.model}",
        "judge": f"{judge.name}:{judge.model}",
        "retrieval": f"{settings.chunk_strategy} chunks, {settings.retrieval_mode}",
        "min_relevance": settings.min_relevance,
    }
    out = settings.results_dir
    # Finished questions are saved as they complete; rerunning resumes.
    checkpoint = out / f"{args.out}.partial.jsonl"
    if args.fresh:
        checkpoint.unlink(missing_ok=True)
    result = evaluate_answers(pipeline, judge, items, checkpoint, config)

    meta = {"date": datetime.now(UTC).strftime("%Y-%m-%d"), **config}
    meta.pop("limit")
    write_json(out / f"{args.out}.json", {"meta": meta, **result})
    checkpoint.unlink(missing_ok=True)
    (out / f"{args.out}.md").write_text(to_markdown(result["summary"], meta), encoding="utf-8")
    print((out / f"{args.out}.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
